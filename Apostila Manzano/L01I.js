// Quadrado da diferença entre dois números
let A = parseInt(prompt("Digite o valor inteiro de A:"));
let B = parseInt(prompt("Digite o valor inteiro de B:"));

let resultado = Math.pow(A - B, 2);

console.log(`O quadrado da diferença entre ${A} e ${B} é: ${resultado}`);
