// Propriedade distributiva (Adição e Multiplicação)
let A = parseInt(prompt("Digite o valor de A:"));
let B = parseInt(prompt("Digite o valor de B:"));
let C = parseInt(prompt("Digite o valor de C:"));
let D = parseInt(prompt("Digite o valor de D:"));

console.log("--- Operações de Adição ---");
console.log(`A + B = ${A + B}`);
console.log(`A + C = ${A + C}`);
console.log(`A + D = ${A + D}`);
console.log(`B + C = ${B + C}`);
console.log(`B + D = ${B + D}`);
console.log(`C + D = ${C + D}`);

console.log("--- Operações de Multiplicação ---");
console.log(`A * B = ${A * B}`);
console.log(`A * C = ${A * C}`);
console.log(`A * D = ${A * D}`);
console.log(`B * C = ${B * C}`);
console.log(`B * D = ${B * D}`);
console.log(`C * D = ${C * D}`);

alert("Resultados gerados! Abra o console (F12) para visualizar todas as 12 operações.");